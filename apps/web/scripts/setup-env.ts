import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

/** Writes apps/web/.env.local with fresh random secrets for local development. */
const file = resolve(import.meta.dirname, "..", ".env.local");
if (existsSync(file)) {
  console.log(`${file} already exists; leaving it alone.`);
  process.exit(0);
}
const content = `# Generated by \`pnpm setup:env\` for local development. Do not commit.
DATABASE_URL=postgres://tokenrank:tokenrank@127.0.0.1:54329/tokenrank
APP_ORIGIN=http://localhost:3000
WEBAUTHN_RP_ID=localhost
SERVER_SECRET=${randomBytes(32).toString("base64url")}
MASTER_KEY=${randomBytes(32).toString("base64")}
CRON_SECRET=${randomBytes(24).toString("base64url")}
# Comma-separated usernames allowed to review flagged usage at /admin/review
ADMIN_USERNAMES=
# SMTP_URL=smtp://user:pass@smtp.example.com:587
# MAIL_FROM=TokenRank <no-reply@example.com>
# ACTIVE_DAY_MIN_TOKENS=1
# SANITY_LIMITS_JSON={"claude_code":5000000000}
`;
writeFileSync(file, content, { mode: 0o600 });
console.log(`Wrote ${file}`);
